export function formatCurrency(amount, currency, language = 'English') {
  const config = CURRENCY_CONFIG[currency] || CURRENCY_CONFIG.USD;
  const value = (Number(amount) || 0) * config.rate;
  const locale = language === 'Urdu' ? 'ur-PK' : config.locale;
  const formatted = new Intl.NumberFormat(locale, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  }).format(value);

  return currency === 'PKR' ? `${config.symbol} ${formatted}` : `${config.symbol}${formatted}`;
}

export function translate(text, language = 'English') {
  return language === 'Urdu' ? (URDU_TRANSLATIONS[text] || text) : text;
}

